// Phase C3: flags at both bases, three hills (the crest, the toe terrace, the river ford), pickups by range.
import { open, exportTo, pickTool, placeAt, setFields } from './.spill-lib-local.mjs';
const [src, out] = process.argv.slice(2);
const { b, page } = await open(src);
const put = async (tool, x, z, fields = []) => { await pickTool(page, tool); const id = await placeAt(page, x, z); if (fields.length) await setFields(page, id, fields); console.log(tool, id); return id; };
const high = (y) => [['Height', y, 'e.position[1]']];
await put('scenario:flag', -104, 16, [['Team', 'embers', 'e.team']]);
await put('scenario:flag', 104, -98, [['Team', 'tide', 'e.team']]);
await exportTo(page, out);
await put('scenario:hill', 0, 62, high(28));
await put('scenario:hill', -22, 30);
await put('scenario:hill', 0, -40);
await exportTo(page, out);
for (const [x, z] of [[-40, 30], [40, 30], [-30, -60], [30, -60]]) await put('pickup:core.health_small', x, z);
await put('pickup:core.health_large', 106, 15);
await put('pickup:core.weapon_sniper', -60, 62, high(28));
await put('pickup:core.weapon_rockets', 60, 62, high(28));
await put('pickup:core.armor_large', -80, 56);
await put('pickup:core.armor_small', 22, 16);
await put('pickup:core.weapon_shotgun', -24, 42);
await put('pickup:core.weapon_rifle', 24, 42);
await put('pickup:core.ammo', 0, -90);
await exportTo(page, out);
await b.close();
