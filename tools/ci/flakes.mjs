#!/usr/bin/env node
// The daily flake list (owner, 2026-11-18): which tests and e2e flows failed and then passed with nothing changed,
// from recent CI runs, with counts. Lane A works it (QUEUE Bugs, the fix batch).
//
//   node tools/ci/flakes.mjs                 the last 7 days of CI runs; writes docs/FLAKES.md
//   node tools/ci/flakes.mjs --days 2        a shorter window
//   node tools/ci/flakes.mjs --print         print the list, write nothing
//
// It counts three ways a check can fail and then pass on the same code:
//   retry     an e2e flow failed and passed on its own retry in the same job (E2E_RETRIES=1: "FLOW x FLAKY")
//   re-run    a job failed in one attempt of a run, and a later attempt of that run succeeded
//   same sha  a run failed and another run for the same commit succeeded
// For a failed job it names the e2e flows ("FLOW x FAIL") or unit tests (vitest's "FAIL file > test") in its log,
// else the job itself. GitHub access as tools/ci/train.mjs has it (`gh api`; GH_REPO=owner/repo, else origin).
// Tested in tools/ci/test/flakes.test.mjs.
import { execFile, execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { repoSlug } from './train.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const run = promisify(execFile);

/** A job log's lines without GitHub's timestamps and colour codes. */
const clean = (text) =>
  String(text)
    .replace(/\x1b\[[0-9;]*m/g, '')
    .split('\n')
    .map((l) => l.replace(/^\d{4}-\d\d-\d\dT[\d:.]+Z ?/, '').replace(/\r$/, ''));

/** The e2e flows a job's log says were flaky (failed, then passed on retry), with the first failed check of each. */
export function flakyFlows(log) {
  const out = new Map();
  for (const l of clean(log)) {
    let m = /^FLOW (\S+) FLAKY\b/.exec(l);
    if (m && !out.has(m[1])) out.set(m[1], '');
    m = /^FLAKY (\S+?): (.*)$/.exec(l);
    if (m) out.set(m[1], m[2].split(' | ')[0].slice(0, 160));
  }
  return [...out].map(([name, why]) => ({ name: `e2e ${name}`, why }));
}

/** What a failed job's log says failed: its e2e flows, else its unit tests, else nothing (the job counts itself). */
export function failedChecks(log) {
  const flows = new Map();
  const tests = new Map();
  for (const l of clean(log)) {
    let m = /^FLOW (\S+) FAIL\b/.exec(l);
    if (m) flows.set(`e2e ${m[1]}`, flows.get(`e2e ${m[1]}`) ?? '');
    m = /^FAIL (\S+?): (.*)$/.exec(l);
    if (m && flows.has(`e2e ${m[1]}`) && !flows.get(`e2e ${m[1]}`)) flows.set(`e2e ${m[1]}`, m[2].slice(0, 160));
    m = /^\s*(?:FAIL|×)\s+(\S+\.test\.[cm]?[jt]s)(?:\s+>\s+(.+?))?(?:\s+\d+m?s)?\s*$/.exec(l);
    if (m) tests.set(m[2] ? `${m[1]} > ${m[2]}` : m[1], '');
  }
  const pick = flows.size ? flows : tests;
  // A file listed alone and with its tests: keep the tests.
  const names = [...pick.keys()];
  return names.filter((n) => !names.some((o) => o !== n && o.startsWith(`${n} > `))).map((name) => ({ name, why: pick.get(name) }));
}

/**
 * One row a check: { name, count, kinds: {retry, 're-run', 'same sha'}, last: { at, url, branch }, why } from
 * events { name, kind, at, url, branch, why }, the most often flaky first.
 */
export function summarize(events) {
  const rows = new Map();
  for (const e of events) {
    const r = rows.get(e.name) ?? { name: e.name, count: 0, kinds: {}, last: null, why: '' };
    r.count++;
    r.kinds[e.kind] = (r.kinds[e.kind] ?? 0) + 1;
    if (!r.last || e.at > r.last.at) {
      r.last = { at: e.at, url: e.url, branch: e.branch };
      if (e.why) r.why = e.why;
    }
    if (!r.why && e.why) r.why = e.why;
    rows.set(e.name, r);
  }
  return [...rows.values()].sort((a, b) => b.count - a.count || (b.last.at > a.last.at ? 1 : -1));
}

/** docs/FLAKES.md. */
export function renderFlakes(rows, { generated, days, runs }) {
  const esc = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ');
  const kinds = (k) => Object.entries(k).map(([n, c]) => `${n} ${c}`).join(', ');
  const head = [
    '# Flaky checks',
    '',
    `Generated by \`node tools/ci/flakes.mjs\` on ${generated} from the last ${days} days of CI runs (${runs} runs read). Don't edit by hand: run it again.`,
    '',
    'Lane A works this list in its daily fix batch (CLAUDE.md, "Fix batches"): root-cause the top entries, and note the fix in HANDOFF. A check counts when it failed and then passed on the same code: **retry** (an e2e flow passed on its own retry in the same job), **re-run** (a job failed, and a later attempt of the run passed), **same sha** (a run failed and another run for the same commit passed).',
    '',
  ];
  if (!rows.length) return [...head, 'Nothing flaky in this window.', ''].join('\n');
  return [
    ...head,
    '| Check | Times | How | Last seen | First failed check (last time) |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${esc(r.name)} | ${r.count} | ${kinds(r.kinds)} | [${r.last.at.slice(0, 10)}](${r.last.url}) ${esc(r.last.branch)} | ${esc(r.why).slice(0, 200)} |`),
    '',
  ].join('\n');
}

async function gh(path, { raw = false } = {}) {
  try {
    const { stdout } = await run('gh', ['api', path], { encoding: 'utf8', maxBuffer: 256 << 20 });
    return raw ? stdout : JSON.parse(stdout);
  } catch {
    return null;
  }
}

/** Run `fn` over `items`, `n` at a time. */
async function pool(items, n, fn) {
  const out = [];
  let i = 0;
  await Promise.all(Array.from({ length: Math.min(n, items.length) }, async () => {
    while (i < items.length) {
      const k = i++;
      out[k] = await fn(items[k]);
    }
  }));
  return out;
}

async function collect(slug, days) {
  const since = new Date(Date.now() - days * 86400000).toISOString().slice(0, 10);
  const runs = [];
  for (let page = 1; page <= 20; page++) {
    const r = await gh(`repos/${slug}/actions/workflows/ci.yml/runs?per_page=100&page=${page}&created=>=${since}`);
    const got = r?.workflow_runs ?? [];
    runs.push(...got);
    if (got.length < 100) break;
  }
  const events = [];
  const jobsOf = async (id, attempt) => (await gh(`repos/${slug}/actions/runs/${id}/attempts/${attempt}/jobs?per_page=100`))?.jobs ?? [];
  const logOf = (job) => gh(`repos/${slug}/actions/jobs/${job.id}/logs`, { raw: true });
  const failedNames = async (job) => {
    const found = failedChecks((await logOf(job)) ?? '');
    return found.length ? found : [{ name: `job ${job.name.replace(/\s*\(\d+\/\d+\)$/, '')}`, why: '' }];
  };
  const add = (r, kind, list) => list.forEach((c) => events.push({ ...c, kind, at: r.updated_at ?? r.created_at, url: r.html_url, branch: r.head_branch }));
  const real = runs.filter((r) => r.status === 'completed' && ['success', 'failure'].includes(r.conclusion));

  // retry: e2e shards that left an e2e-flaky-<i> artifact (runs long enough to have run e2e).
  const long = real.filter((r) => Date.parse(r.updated_at) - Date.parse(r.run_started_at ?? r.created_at) > 4 * 60000);
  await pool(long, 8, async (r) => {
    const arts = (await gh(`repos/${slug}/actions/runs/${r.id}/artifacts?per_page=100`))?.artifacts ?? [];
    const shards = arts.map((a) => /^e2e-flaky-(\d+)$/.exec(a.name)?.[1]).filter(Boolean);
    if (!shards.length) return;
    const jobs = await jobsOf(r.id, r.run_attempt);
    for (const s of shards) {
      const job = jobs.find((j) => new RegExp(`^e2e \\(${s}/\\d+\\)$`).test(j.name));
      if (job) add(r, 'retry', flakyFlows((await logOf(job)) ?? ''));
    }
  });

  // re-run: a failed attempt of a run whose latest attempt succeeded.
  await pool(real.filter((r) => r.run_attempt > 1 && r.conclusion === 'success'), 4, async (r) => {
    for (let a = 1; a < r.run_attempt; a++) {
      const failed = (await jobsOf(r.id, a)).filter((j) => j.conclusion === 'failure');
      for (const j of failed) add(r, 're-run', await failedNames(j));
    }
  });

  // same sha: a failed run with a successful run for the same commit.
  const green = new Set(real.filter((r) => r.conclusion === 'success').map((r) => r.head_sha));
  await pool(real.filter((r) => r.conclusion === 'failure' && green.has(r.head_sha)), 4, async (r) => {
    const failed = (await jobsOf(r.id, r.run_attempt)).filter((j) => j.conclusion === 'failure');
    for (const j of failed) add(r, 'same sha', await failedNames(j));
  });
  return { events, runs: runs.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--days');
  const days = i >= 0 ? Number(argv[i + 1]) : 7;
  if (!(days > 0)) {
    console.error('flakes: --days needs a number of days');
    process.exit(1);
  }
  const slug = process.env.GH_REPO || repoSlug(execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: ROOT, encoding: 'utf8' }));
  if (!slug) {
    console.error('flakes: cannot tell the GitHub repository from origin: set GH_REPO=owner/repo');
    process.exit(1);
  }
  const { events, runs } = await collect(slug, days);
  if (!runs) {
    console.error('flakes: no CI runs read (is `gh api` working?)');
    process.exit(1);
  }
  const md = renderFlakes(summarize(events), { generated: new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC', days, runs });
  if (argv.includes('--print')) console.log(md);
  else {
    writeFileSync(new URL('../../docs/FLAKES.md', import.meta.url), md);
    console.log(`docs/FLAKES.md: ${summarize(events).length} flaky checks from ${runs} runs (${days} days).`);
  }
}
