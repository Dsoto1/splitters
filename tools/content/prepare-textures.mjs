// Downloads the ambientCG material sets listed in content/textures.json and
// writes 512 px colour / normal / emission JPEGs to packages/client/public/textures,
// plus content/textures.lock.json (hashes, sizes) that `pnpm content:check` verifies.
//
//   node tools/content/prepare-textures.mjs [--only <id,id,...>]
//
// --only fetches just those sets (new ones added to the manifest) and keeps
// every other set as already built, so adding a texture leaves the rest alone.
//
// Needs `curl` and `unzip` on the PATH. Sources are not kept: the lock file
// records exactly which ambientCG set and download each output came from.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { writeLock } from './lockfile.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'content/textures.json'), 'utf8'));
const OUT = join(ROOT, 'packages/client/public/textures');
mkdirSync(OUT, { recursive: true });

const MAPS = [
  ['_Color.jpg', 'color'],
  ['_NormalGL.jpg', 'normal'],
  ['_Emission.jpg', 'emission'],
];
/**
 * A set's colour map, adjusted as content/textures.json's `adjust` says: `contrast` (0-1) pulls every pixel toward
 * the map's mean colour by that factor (1 unchanged), e.g. a speckled floor whose specks shout at phone size.
 */
async function adjusted(img, kind, adjust) {
  if (kind !== 'color' || !adjust?.contrast || adjust.contrast === 1) return img;
  const pixels = await img.clone().removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const mean = [0, 0, 0];
  for (let i = 0; i < pixels.data.length; i += 3) for (let c = 0; c < 3; c++) mean[c] += pixels.data[i + c];
  const n = pixels.data.length / 3;
  const a = adjust.contrast;
  return sharp(pixels.data, { raw: pixels.info }).linear([a, a, a], mean.map((m) => (m / n) * (1 - a)));
}
const only = process.argv.includes('--only') ? new Set((process.argv[process.argv.indexOf('--only') + 1] ?? '').split(',')) : null;
const LOCK = join(ROOT, 'content/textures.lock.json');
const oldLock = JSON.parse(readFileSync(LOCK, 'utf8'));
const lock = { $comment: 'Generated by tools/content/prepare-textures.mjs. Do not edit by hand.', files: [] };
const work = mkdtempSync(join(tmpdir(), 'cs-tex-'));
try {
  for (const id of manifest.textures) {
    if (only && !only.has(id)) {
      lock.files.push(...oldLock.files.filter((f) => f.asset === id));
      continue;
    }
    const url = `https://ambientcg.com/get?file=${id}_1K-JPG.zip`;
    const zip = join(work, `${id}.zip`);
    execFileSync('curl', ['-sSfL', '-o', zip, url]);
    const dir = join(work, id);
    mkdirSync(dir);
    execFileSync('unzip', ['-q', '-o', zip, '-d', dir]);
    for (const [suffix, kind] of MAPS) {
      const src = readdirSync(dir).find((f) => f.endsWith(suffix));
      if (!src) continue;
      const out = `${id}_${kind}.jpg`;
      const data = await adjusted(sharp(join(dir, src)).resize(manifest.size, manifest.size, { kernel: 'lanczos3' }), kind, manifest.adjust?.[id]).then((img) => img.jpeg({ quality: 82, progressive: true, mozjpeg: true }).toBuffer());
      writeFileSync(join(OUT, out), data);
      lock.files.push({ file: `textures/${out}`, asset: id, map: kind, source: url, bytes: data.byteLength, sha256: createHash('sha256').update(data).digest('hex').slice(0, 16) });
    }
    rmSync(zip);
    rmSync(dir, { recursive: true });
    console.log(id);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
writeLock(LOCK, lock);
