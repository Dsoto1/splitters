// Downloads the ambientCG material sets listed in content/textures.json and
// writes 512 px colour / normal / emission JPEGs to packages/client/public/textures,
// plus content/textures.lock.json (hashes, sizes) that `pnpm content:check` verifies.
//
//   node tools/content/prepare-textures.mjs
//
// Needs `curl` and `unzip` on the PATH. Sources are not kept: the lock file
// records exactly which ambientCG set and download each output came from.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'content/textures.json'), 'utf8'));
const OUT = join(ROOT, 'packages/client/public/textures');
mkdirSync(OUT, { recursive: true });

const MAPS = [
  ['_Color.jpg', 'color'],
  ['_NormalGL.jpg', 'normal'],
  ['_Emission.jpg', 'emission'],
];
const lock = { $comment: 'Generated by tools/content/prepare-textures.mjs. Do not edit by hand.', files: [] };
const work = mkdtempSync(join(tmpdir(), 'cs-tex-'));
try {
  for (const id of manifest.textures) {
    const url = `https://ambientcg.com/get?file=${id}_1K-JPG.zip`;
    const zip = join(work, `${id}.zip`);
    execFileSync('curl', ['-sSfL', '-o', zip, url]);
    const dir = join(work, id);
    mkdirSync(dir);
    execFileSync('unzip', ['-q', '-o', zip, '-d', dir]);
    for (const [suffix, kind] of MAPS) {
      const src = readdirSync(dir).find((f) => f.endsWith(suffix));
      if (!src) continue;
      const out = `${id}_${kind}.jpg`;
      const data = await sharp(join(dir, src)).resize(manifest.size, manifest.size, { kernel: 'lanczos3' }).jpeg({ quality: 82, progressive: true, mozjpeg: true }).toBuffer();
      writeFileSync(join(OUT, out), data);
      lock.files.push({ file: `textures/${out}`, asset: id, map: kind, source: url, bytes: data.byteLength, sha256: createHash('sha256').update(data).digest('hex').slice(0, 16) });
    }
    rmSync(zip);
    rmSync(dir, { recursive: true });
    console.log(id);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
writeFileSync(join(ROOT, 'content/textures.lock.json'), `${JSON.stringify(lock, null, 2)}\n`);
