// Renders every weapon model's side-on icon for the kill feed and the loadout, so the site ships them as
// small pictures instead of building a weapon model (and compiling its shaders) in the middle of a fight
// the first time someone is killed with it:
//   packages/client/public/weapon-icons/<model>.webp      128×56 WebP, transparent background
//   packages/client/src/frontend/weaponIconIndex.ts        which models have one (and a hash, so a new one is fetched)
// The pictures come from the same renderer the game uses (frontend/modelThumbs.ts, the 'side' view):
// framing fixes there show up here on the next capture. A model without a shipped icon is rendered live.
//
// Run against a built client being served (the "Capture portraits" workflow does all of this):
//   pnpm build && pnpm --filter @tiletrigger/client exec vite preview --port 4799
//   node tools/content/capture-weapon-icons.mjs http://localhost:4799 [model paths…]
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = join(ROOT, 'packages/client/public/weapon-icons');
const INDEX = join(ROOT, 'packages/client/src/frontend/weaponIconIndex.ts');
const base = process.argv[2] ?? 'http://localhost:4799';
const only = process.argv.slice(3);

/** A model path as a file name (paths are like models/weapons/rifle.glb). */
const fileOf = (model) => `${model.replace(/\.[a-z0-9]+$/i, '').replace(/[^A-Za-z0-9_.-]/g, '_')}.webp`;

mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${base}/?test=1&name=Tester`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__weaponIcons, null, { timeout: 120_000 });
const models = (await page.evaluate(() => window.__weaponIcons.models())).filter((m) => !only.length || only.includes(m));
console.log(`${models.length} weapon models`);

// The index: a full run starts it again (pictures of models that are gone are deleted); a partial run
// (model paths on the command line) keeps the other entries as they were.
const index = {};
if (only.length) for (const m of readFileSync(INDEX, 'utf8').matchAll(/^ {2}'([^']+)': '([^']+)',$/gm)) index[m[1]] = m[2];
const failed = [];
for (const model of models) {
  const url = await page.evaluate((m) => window.__weaponIcons.render(m), model).catch((e) => {
    failed.push(`${model}: ${e.message}`);
    return null;
  });
  if (!url) continue;
  const png = Buffer.from(url.slice(url.indexOf(',') + 1), 'base64');
  const webp = await sharp(png).webp({ quality: 86, alphaQuality: 90 }).toBuffer();
  writeFileSync(join(OUT, fileOf(model)), webp);
  index[model] = `${fileOf(model)}?v=${createHash('sha256').update(webp).digest('hex').slice(0, 10)}`;
  console.log(`${model}: ${(webp.length / 1024).toFixed(1)} kB`);
}
await browser.close();
if (!only.length) {
  const keep = new Set(Object.values(index).map((v) => v.split('?')[0]));
  for (const f of readdirSync(OUT)) if (f.endsWith('.webp') && !keep.has(f)) rmSync(join(OUT, f));
}

const lines = Object.keys(index)
  .sort()
  .map((k) => `  '${k}': '${index[k]}',`);
writeFileSync(
  INDEX,
  `/**
 * Weapon icons shipped with the site (public/weapon-icons/), by model file:
 * the picture and a hash of it (so a new one is fetched, not a cached old one).
 * Generated by tools/content/capture-weapon-icons.mjs (the "Capture portraits"
 * workflow) from the same renderer the game uses; a model missing here is
 * rendered live.
 */
export const SHIPPED_WEAPON_ICONS: Readonly<Record<string, string>> = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`,
);
console.log(`index: ${Object.keys(index).length} weapon icons`);
if (failed.length || errors.length) {
  console.error(`failed: ${failed.join('; ')}${errors.length ? ` · page errors: ${errors.join('; ')}` : ''}`);
  process.exit(1);
}
