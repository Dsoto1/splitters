// content/vfx.json's `map` (which effect plays where) → packages/client/src/game/fxMap.generated.ts.
//
//   node tools/content/vfx-map.mjs           write it
//   (content:check, tools/content/build.mjs --check, fails when it is stale or names an effect that isn't shipped)
//
// prepare-vfx.mjs writes only the hit and explosion effects the map names (and a pack's `keep`), so a
// match fetches what it plays and nothing else.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const FX_MAP_FILE = join(ROOT, 'packages/client/src/game/fxMap.generated.ts');

export function readVfxManifest() {
  return JSON.parse(readFileSync(join(ROOT, 'content/vfx.json'), 'utf8'));
}

/** Drop `$comment` keys, recursively. */
function strip(v) {
  if (Array.isArray(v)) return v.map(strip);
  if (!v || typeof v !== 'object') return v;
  return Object.fromEntries(Object.entries(v).filter(([k]) => k !== '$comment').map(([k, x]) => [k, strip(x)]));
}

/** Every { pack, effect } the map names, by pack file (hit_fx, explosion_fx, electric_fx …), plus the muzzle flashes. */
export function referencedEffects(manifest = readVfxManifest()) {
  const map = strip(manifest.map);
  const out = { muzzle_flash: new Set() };
  for (const p of Object.values(manifest.packs)) if (p.file) out[p.file] = new Set(p.keep ?? []);
  const visit = (v) => {
    if (!v || typeof v !== 'object') return;
    if (typeof v.pack === 'string' && typeof v.effect === 'string') {
      if (!out[v.pack]) throw new Error(`content/vfx.json map: unknown pack ${v.pack}`);
      out[v.pack].add(v.effect);
      return;
    }
    for (const x of Object.values(v)) visit(x);
  };
  visit(Object.fromEntries(Object.entries(map).filter(([k]) => k !== 'muzzle' && k !== 'surfaces')));
  for (const m of Object.values(map.muzzle)) out.muzzle_flash.add(m.effect);
  return out;
}

export function fxMapSource(manifest = readVfxManifest()) {
  const map = strip(manifest.map);
  return `// Generated by tools/content/vfx-map.mjs from content/vfx.json's \`map\`. Do not edit by hand.
// Which effect plays where: muzzle flashes by weapon family, impacts by surface, explosions by weapon and
// kind, moments of play (pickups, spawns, portals, jump pads, traps, ziplines) and the effects that last (fire,
// charge balls, glows). game/fxMap.ts reads it.

export const FX_MAP = ${JSON.stringify(map, null, 2)} as const;
`;
}

/** Problems for content:check: the generated file is stale, or the map names an effect that isn't shipped. */
export function checkFxMap(root = ROOT) {
  const problems = [];
  const manifest = readVfxManifest();
  if (!existsSync(FX_MAP_FILE) || readFileSync(FX_MAP_FILE, 'utf8') !== fxMapSource(manifest)) problems.push('packages/client/src/game/fxMap.generated.ts: stale (run node tools/content/vfx-map.mjs)');
  const refs = referencedEffects(manifest);
  for (const [file, names] of Object.entries(refs)) {
    const path = join(root, 'packages/client/public/vfx', `${file}.json`);
    if (!existsSync(path)) continue;
    const shipped = JSON.parse(readFileSync(path, 'utf8')).effects;
    for (const n of names) if (!shipped[n]) problems.push(`content/vfx.json map: ${file} has no effect ${n} (run node tools/content/prepare-vfx.mjs --downloads <dir>)`);
  }
  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(FX_MAP_FILE, fxMapSource());
  console.log(`wrote ${FX_MAP_FILE}`);
}
