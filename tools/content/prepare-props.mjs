// Builds the placeable props listed in content/props.json: each is centred on
// its footprint, stood on y = 0, scaled to its real-world height (or kept at
// the pack's own metric scale), and written as a self-contained GLB (textures
// embedded) to packages/client/public/props. Also writes
// content/props.lock.json (checked by `pnpm content:check`) and
// packages/shared/src/content/props.generated.ts, the sizes and collision
// boxes the simulation, bots and MapMaker use.
//
//   node tools/content/prepare-props.mjs [--downloads <dir>]
//
// Most packs live in assets-src/<pack>/. Packs with a `download` folder in
// content/props.json (the Quaternius Modular SciFi MegaKit, and the Kenney
// kits behind the Style Packs) stay out of the repo: their props are rebuilt only when --downloads points at a
// directory holding the extracted download (directly or one level down);
// otherwise (or when that pack's folder is not there) the props already built
// from them are kept as they are.
//
// Packs with `convert: true` (FBX-only packs and one-scene sets: Designersoup's
// cars, the household items, Elbolillo's gas station and metro) are read with
// tools/content/fbx.mjs (or as GLB), one prop per `src`: `file.fbx` or
// `file.fbx#<regex>` to keep only the scene's objects whose name (or a parent's)
// matches. `flatten` packs lose their (third-party photo) textures for a flat
// colour per face (tools/content/flatten.mjs).
//
// Packs with `meshy: true` (Meshy community downloads, CC0 per the owner) are
// Meshy's textured FBX folders, one per prop (the prop's own `download`):
// tools/content/meshy-mesh.mjs cuts each to `triangles` and paints its colour
// map afresh onto new charts (`surface`, default `rebake`), dropping what can't
// be seen from outside first where `dropHidden` says so; `stone` turns the
// colour map to weathered stone of that colour (a statue).

