/**
 * A single-file GLB (the Kenney kits and our own code-built pieces): centred on
 * its footprint, stood on y = 0 and scaled to the prop's `height`.
 */
async function normaliseGlb(src, p) {
  const doc = await io.read(src);
  const scene = doc.getRoot().listScenes()[0];
  const b = getBounds(scene);
  const s = p.height / Math.max(1e-6, b.max[1] - b.min[1]);
  const cx = (b.min[0] + b.max[0]) / 2;
  const cz = (b.min[2] + b.max[2]) / 2;
  const root = doc.createNode('prop').setScale([s, s, s]).setTranslation([-cx * s, -b.min[1] * s, -cz * s]);
  for (const child of scene.listChildren()) {
    scene.removeChild(child);
    root.addChild(child);
  }
  scene.addChild(root);
  await doc.transform(weld(), dedup(), prune());
  return { glb: Buffer.from(await io.writeBinary(doc)), size: [round((b.max[0] - b.min[0]) * s), round(p.height), round((b.max[2] - b.min[2]) * s)] };
}

const linear = (hex) => [1, 3, 5].map((i) => {
  const c = parseInt(hex.slice(i, i + 2), 16) / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
});

/** Cut a triangle ([{ p, n }] × 3) by the plane at height y: the pieces either side, each a triangle, winding kept. */
function cutTriangle(tri, y) {
  const side = tri.map((v) => v.p[1] > y);
  const up = side.filter(Boolean).length;
  if (up === 0 || up === 3) return [tri];
  // Rotate so the lone vertex (the one on its own side) comes first.
  const lone = side.findIndex((s) => s === (up === 1));
  const [a, b, c] = [tri[lone], tri[(lone + 1) % 3], tri[(lone + 2) % 3]];
  const at = (u, v) => {
    const t = (y - u.p[1]) / (v.p[1] - u.p[1]);
    const mix = (x, z) => x.map((q, i) => q + (z[i] - q) * t);
    const n = mix(u.n, v.n);
    const l = Math.hypot(...n) || 1;
    return { p: mix(u.p, v.p), n: n.map((q) => q / l) };
  };
  const ab = at(a, b);
  const ac = at(a, c);
  return [[a, ab, ac], [ab, b, c], [ab, c, ac]];
}

/**
 * Colours for a pack that ships untextured grey materials (madduck's hospital
 * set): `colors` gives each material (by name) a flat colour, or
 * `{ color, emissive, alpha }`; `meshColors` colours whole objects by a name
 * regex (door handles); a prop's own `colors` override the pack's, and its
 * `bands` ([[from, colour], …], `from` a fraction of the model's height) paint
 * each face by the height of its centre (legs, seat, mattress; a wall's dado),
 * as vertex colours on the opaque materials.
 */
async function paintFlat(doc, pack, p) {
  const colors = { ...pack.colors, ...(p.colors ?? {}) };
  const spec = (name) => {
    const c = colors[name];
    return typeof c === 'string' ? { color: c } : c;
  };
  for (const mat of doc.getRoot().listMaterials()) {
    const c = spec(mat.getName());
    if (!c) continue;
    mat.setBaseColorFactor([...linear(c.color), c.alpha ?? 1]);
    if (c.alpha !== undefined && c.alpha < 1) mat.setAlphaMode('BLEND');
    if (c.emissive) mat.setEmissiveFactor(linear(c.emissive));
  }
  const byMesh = Object.entries(pack.meshColors ?? {}).map(([re, hex]) => [new RegExp(re), hex]);
  if (!p.bands && !byMesh.some(([re]) => doc.getRoot().listMeshes().some((m) => re.test(m.getName())))) return;
  await doc.transform(unweld());
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const h = Math.max(1e-6, b.max[1] - b.min[1]);
  const buffer = doc.getRoot().listBuffers()[0];
  // Meshes painted whole get a material of their own (white, so the vertex colour shows as it is).
  const painted = new Map();
  for (const mesh of doc.getRoot().listMeshes()) {
    const whole = byMesh.find(([re]) => re.test(mesh.getName()))?.[1];
    for (const prim of mesh.listPrimitives()) {
      const mat = prim.getMaterial();
      if (!mat || mat.getAlphaMode() === 'BLEND') continue;
      if (!whole && !p.bands) continue;
      const base = mat.getBaseColorFactor();
      const pos = prim.getAttribute('POSITION');
      const nrm = prim.getAttribute('NORMAL');
      // Faces that straddle a band's edge are cut along it, so each band is painted exactly where it starts.
      const cuts = whole ? [] : p.bands.slice(1).map(([from]) => b.min[1] + from * h);
      let tris = [];
      for (let t = 0; t + 2 < pos.getCount(); t += 3) tris.push([0, 1, 2].map((k) => ({ p: pos.getElement(t + k, []), n: nrm ? nrm.getElement(t + k, []) : [0, 1, 0] })));
      for (const y of cuts) tris = tris.flatMap((tri) => cutTriangle(tri, y));
      const P = new Float32Array(tris.length * 9);
      const N = new Float32Array(tris.length * 9);
      const out = new Float32Array(tris.length * 12);
      tris.forEach((tri, t) => {
        const f = (tri.reduce((y, v) => y + v.p[1], 0) / 3 - b.min[1]) / h;
        const hex = whole ?? [...p.bands].reverse().find(([from]) => f >= from)?.[1];
        const c = hex ? [...linear(hex), 1] : base;
        tri.forEach((v, k) => {
          P.set(v.p, (t * 3 + k) * 3);
          N.set(v.n, (t * 3 + k) * 3);
          out.set(c, (t * 3 + k) * 4);
        });
      });
      for (const sem of prim.listSemantics()) prim.setAttribute(sem, null);
      prim.setIndices(null);
      prim.setAttribute('POSITION', doc.createAccessor().setType('VEC3').setArray(P).setBuffer(buffer));
      if (nrm) prim.setAttribute('NORMAL', doc.createAccessor().setType('VEC3').setArray(N).setBuffer(buffer));
      prim.setAttribute('COLOR_0', doc.createAccessor().setType('VEC4').setArray(out).setBuffer(buffer));
      if (!painted.has(mat)) painted.set(mat, mat.clone().setBaseColorFactor([1, 1, 1, base[3]]));
      prim.setMaterial(painted.get(mat));
    }
  }
}

/**
 * `stone`: a colour map turned to weathered stone of the given colour, keeping its light and shade (each pixel's
 * brightness against the map's average) so carved detail still reads.
 */
function stone({ data }, hex) {
  const tint = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  let mean = 0;
  for (let i = 0; i < data.length; i += 3) mean += data[i] * 0.3 + data[i + 1] * 0.59 + data[i + 2] * 0.11;
  mean /= data.length / 3;
  for (let i = 0; i < data.length; i += 3) {
    const l = (data[i] * 0.3 + data[i + 1] * 0.59 + data[i + 2] * 0.11) / mean;
    for (let ch = 0; ch < 3; ch++) data[i + ch] = Math.min(255, Math.round(tint[ch] * (0.45 + 0.55 * l)));
  }
}

/**
 * A hero piece's lower level of detail (`lod` on a prop: [share of the triangles, metres from which it is drawn]):
 * big landmark pieces carry three to four times a small prop's triangles up close, and about a small prop's from here on.
 */
const HERO_LOD = [0.25, 40];

/**
 * The size of a Meshy prop's baked normal map (px): `normalSize` on the prop or its pack, else half its colour map
 * (`textureSize` on the prop, else the pack's). 0: none.
 */
function normalSizeOf(pack, p) {
  if (!pack.meshy) return 0;
  const size = p.normalSize ?? pack.normalSize ?? (p.textureSize ?? pack.textureSize) / 2;
  return Math.max(0, Math.min(1024, size ?? 256));
}

/** A prop from a `convert` pack: picked from its FBX/GLB, flattened if asked, turned, centred, stood on the ground and scaled. */
async function convertPiece(dir, pack, p) {
  const [file, pickSrc] = p.src.split('#');
  const path = join(dir, pack.models ?? '.', file);
  const pick = pickSrc ? new RegExp(pickSrc) : null;
  let doc;
  if (pack.meshy) ({ doc } = await meshyDocument(path, { triangles: p.triangles, maxError: p.maxError, surface: p.surface ?? 'rebake', dropHidden: p.dropHidden, normalSize: normalSizeOf(pack, p) ? 1024 : 0, lod: p.lod ?? (p.budget === 'hero' ? HERO_LOD : null), recolor: p.stone ? (map) => stone(map, p.stone) : null }));
  else if (/\.fbx$/i.test(file)) ({ doc } = await fbxToDocument(path, { pick }));
  else {
    doc = await io.read(path);
    doc.setLogger(quiet);
    // Drop whole subtrees: the objects not picked, and collision-only meshes (Unity's `-colonly` convention).
    const drop = (n) => {
      for (const c of n.listChildren()) drop(c);
      n.dispose();
    };
    for (const n of doc.getRoot().listScenes()[0].listChildren()) if (pick && !pick.test(n.getName())) drop(n);
    for (const n of doc.getRoot().listNodes()) if (/-colonly$/.test(n.getName())) drop(n);
    await doc.transform(prune());
  }
  doc.setLogger(quiet);
  // `maps`: colour maps that sit beside the model unlinked (the Mines and Caves set), by material name.
  for (const [name, file] of Object.entries(pack.maps ?? {})) {
    const mats = doc.getRoot().listMaterials().filter((m) => m.getName() === name);
    if (!mats.length) continue;
    const tex = doc.createTexture(name).setImage(readFileSync(join(dir, file))).setMimeType('image/png');
    for (const m of mats) m.setBaseColorTexture(tex).setBaseColorFactor([1, 1, 1, 1]);
  }
  // `dropEmissive`: Meshy's FBX give every material a white emissive colour (meant for its emission map).
  if (pack.dropEmissive) for (const m of doc.getRoot().listMaterials()) m.setEmissiveFactor([0, 0, 0]).setEmissiveTexture(null);
  // Vertex colours some exports carry as painting masks, not colours.
  if (pack.dropVertexColors) for (const mesh of doc.getRoot().listMeshes()) for (const prim of mesh.listPrimitives()) prim.setAttribute('COLOR_0', null);
  // `flatten` on a prop: only those pieces carry third-party photo maps (loafbrr's metal fence).
  if (pack.flatten || p.flatten) await flattenTextures(doc);
  if (pack.colors) await paintFlat(doc, pack, p);
  for (const mat of doc.getRoot().listMaterials()) {
    // Meshy props keep the normal map baked from the full download (meshy-mesh.mjs); other kits' maps go.
    mat.setMetallicRoughnessTexture(null).setOcclusionTexture(null).setMetallicFactor(0).setRoughnessFactor(0.8);
    if (!pack.meshy) mat.setNormalTexture(null);
    for (const ext of mat.listExtensions()) ext.dispose();
    if (/glass/i.test(mat.getName())) mat.setBaseColorFactor([0.3, 0.38, 0.42, 0.45]).setAlphaMode('BLEND').setRoughnessFactor(0.15);
  }
  const scene = doc.getRoot().listScenes()[0];
  const turn = doc.createNode('turn').setRotation(yawQuat(p.yaw ?? 0));
  for (const child of scene.listChildren()) {
    scene.removeChild(child);
    turn.addChild(child);
  }
  scene.addChild(turn);
  const b = getBounds(scene);
  const s = p.height ? p.height / Math.max(1e-6, b.max[1] - b.min[1]) : (p.scale ?? pack.scale ?? 1);
  const root = doc.createNode('prop').setScale([s, s, s]).setTranslation([(-(b.min[0] + b.max[0]) / 2) * s, -b.min[1] * s + (p.lift ?? 0), (-(b.min[2] + b.max[2]) / 2) * s]);
  scene.removeChild(turn);
  root.addChild(turn);
  scene.addChild(root);
  if (p.simplify) {
    // Flat-shaded exports split every face apart by its normal, which leaves the simplifier nothing to
    // collapse: drop the normals, simplify the welded mesh, then give each face its own normal again.
    for (const mesh of doc.getRoot().listMeshes()) for (const prim of mesh.listPrimitives()) prim.setAttribute('NORMAL', null);
    await doc.transform(weld(), simplify({ simplifier: MeshoptSimplifier, ratio: p.simplify, error: 0.01 }), unweld(), normals({ overwrite: true }));
  }
  await doc.transform(weld(), dedup(), prune(), quantize(pack.meshy ? MESHY_QUANTIZE : undefined));
  // Embedded textures: palettes (the cars') as small PNGs, painted maps (`textureSize`) as JPEGs.
  const normalMaps = new Set(doc.getRoot().listMaterials().map((m) => m.getNormalTexture()).filter(Boolean));
  for (const t of doc.getRoot().listTextures()) {
    if (normalMaps.has(t)) {
      t.setImage(await normalJpeg(t.getImage(), normalSizeOf(pack, p))).setMimeType('image/jpeg').setURI('');
      continue;
    }
    const textureSize = p.textureSize ?? pack.textureSize;
    if (textureSize) {
      const img = sharp(Buffer.from(t.getImage())).resize(textureSize, textureSize, { fit: 'inside', kernel: 'lanczos3' });
      t.setImage(await img.removeAlpha().jpeg({ quality: 80, mozjpeg: true }).toBuffer()).setMimeType('image/jpeg').setURI('');
      continue;
    }
    const img = sharp(Buffer.from(t.getImage())).resize(128, 128, { fit: 'inside', kernel: 'nearest' });
    t.setImage(await img.png({ palette: true }).toBuffer()).setMimeType('image/png').setURI('');
  }
  return Buffer.from(await io.writeBinary(doc));
}

/**
 * A prop from a `nature` pack (the Meshy community plants, trees and rocks):
 * decimated, painted per face and given levels of detail by tools/content/nature.mjs.
 * `nature` on the prop: `lods` [[triangles, distance], …] (LOD0 first; distance where
 * it gives way to the next), `impostor` (distance of the camera-facing card, or
 * none), `remesh` (voxel cells; `shell` for open leaves), `flags` for the
 * simplifier, `cut` (share of the raw height to cut off the bottom: a scene's
 * ground plate), `doubleSided`.
 */
async function natureProp(dir, pack, p) {
  const n = p.nature;
  let soup = await readSoup(join(dir, p.src));
  const cut = n.cut ?? 0;
  const total = p.height / (1 - cut);
  normalise(soup.P, { yaw: p.yaw ?? 0, height: total });
  if (cut) {
    soup = cutBelow(soup, total * cut);
    for (let i = 1; i < soup.P.length; i += 3) soup.P[i] -= total * cut;
  }
  const lods = n.lods.map(([triangles, distance]) => ({ triangles, distance }));
  const { doc } = await buildNatureDocument(soup, {
    lods,
    impostor: n.impostor ? { distance: n.impostor, size: 256 } : null,
    remesh: n.remesh ?? 0,
    shell: !!n.shell,
    flags: n.flags ?? ['Prune'],
    doubleSided: !!n.doubleSided,
    name: p.id,
  });
  // Centred on LOD0's footprint after the cut.
  const lod0 = doc.getRoot().listNodes()[0];
  const b = getBounds(lod0);
  for (const node of doc.getRoot().listNodes()) node.setTranslation([-(b.min[0] + b.max[0]) / 2, -b.min[1], -(b.min[2] + b.max[2]) / 2]);
  // Face normals need no more than 8 bits.
  await doc.transform(dedup(), prune(), quantize({ quantizeNormal: 8 }));
  return { glb: Buffer.from(await io.writeBinary(doc)), size: [round(b.max[0] - b.min[0]), round(b.max[1] - b.min[1]), round(b.max[2] - b.min[2])] };
}

for (const p of manifest.props) {
  const pack = manifest.packs[p.pack];
  const file = `props/${p.id}.glb`;
  const path = join(ROOT, 'packages/client/public', file);
  // A pack with a `download` folder is rebuilt only from a downloads directory (it stays out of the
  // repo), except for pieces of it already kept in assets-src/ (older imports of the same kit).
  const local = !Array.isArray(p.src) && existsSync(join(ROOT, 'assets-src', p.pack, p.src));
  // Meshy packs name each prop's own download folder (`download` on the prop).
  const external = !!(p.download ?? pack.download) && !local;
  // Packs with an `images` folder (the MegaKit's glTF, the Orbital and Neon Kenney kits) get their materials
  // baked and shrunk; other GLB kits are normalised as they are.
  const gltfKit = external && !!pack.images;
  const converted = external && (!!pack.convert || !!pack.nature);
  // ONLY=<id>,<id> rebuilds just those props from the downloads (the rest are kept as built and checked).
  const dir = external && downloads && (!only || only.includes(p.id)) ? downloadDir(p.download ?? pack.download) : null;
  let glb;
  let size;
  if (gltfKit && dir) {
    const srcs = Array.isArray(p.src) ? p.src : [p.src];
    const doc = await readPieces(srcs.map((s) => join(dir, pack.models, s)), join(dir, pack.images));
    await bakeKitMaterials(doc, pack);
    const scene = doc.getRoot().listScenes()[0];
    const turn = doc.createNode('turn').setRotation(yawQuat(p.yaw ?? 0));
    for (const child of scene.listChildren()) {
      scene.removeChild(child);
      turn.addChild(child);
    }
    scene.addChild(turn);
    const b = getBounds(scene);
    const s = p.height ? p.height / Math.max(1e-6, b.max[1] - b.min[1]) : (p.scale ?? 1);
    const root = doc.createNode('prop').setScale([s, s, s]).setTranslation([(-(b.min[0] + b.max[0]) / 2) * s, -b.min[1] * s + (p.lift ?? 0), (-(b.min[2] + b.max[2]) / 2) * s]);
    scene.removeChild(turn);
    root.addChild(turn);
    scene.addChild(root);
    await doc.transform(weld(), dedup(), ...(p.simplify ? [simplify({ simplifier: MeshoptSimplifier, ratio: p.simplify, error: 0.002 })] : []), prune());
    glb = Buffer.from(await io.writeBinary(doc));
    writeFileSync(path, glb);
  } else if (external && pack.nature && dir) {
    ({ glb, size } = await natureProp(dir, pack, p));
    writeFileSync(path, glb);
  } else if (converted && dir) {
    glb = await convertPiece(dir, pack, p);
    writeFileSync(path, glb);
  } else if (external && dir) {
    ({ glb, size } = await normaliseGlb(join(dir, pack.models, p.src), p));
    writeFileSync(path, glb);
  } else if (external) {
    // Not rebuilding this pack: keep the prop as built (already normalised) and measure it again.
    if (!existsSync(path)) throw new Error(`${file} is missing; rebuild it with --downloads <dir> (see docs/CONTENT_PIPELINE.md)`);
    glb = readFileSync(path);
    const was = built.get(file);
    if (was?.sha256 !== createHash('sha256').update(glb).digest('hex').slice(0, 16)) throw new Error(`${file} does not match content/props.lock.json; rebuild it with --downloads <dir>`);
    if (was.size) size = was.size;
  } else {
    ({ glb, size } = await normaliseGlb(join(ROOT, 'assets-src', p.pack, p.src), p));
    writeFileSync(path, glb);
  }
  // Measure what was written (the same whether it was just built or kept).
  const doc = await io.readBinary(new Uint8Array(glb));
  const scene = doc.getRoot().listScenes()[0];
  let triangles = 0;
  // Lower levels of detail (nature.mjs) are counted apart: the budget is for the full-detail model.
  const lodTriangles = [];
  for (const mesh of doc.getRoot().listMeshes()) {
    let t = 0;
    for (const prim of mesh.listPrimitives()) t += (prim.getIndices()?.getCount() ?? prim.getAttribute('POSITION').getCount()) / 3;
    if (mesh.listParents().some((n) => n.propertyType === 'Node' && n.getExtras()?.lod)) lodTriangles.push(t);
    else triangles += t;
  }
  if (!size) {
    const b = getBounds(scene);
    // Flat pieces (floor plates, decals) are lifted a little off the floor; their footprint still starts at 0.
    size = [round(b.max[0] - b.min[0]), round(Math.max(b.max[1], 0.01)), round(b.max[2] - b.min[2])];
  }
  const thick = (v) => round(Math.max(v, MIN_THICKNESS));
  const collision = p.collide === 'none' ? null : p.collide === 'trunk' ? [Math.min(0.5, size[0]), size[1], Math.min(0.5, size[2])] : gltfKit || converted ? [thick(size[0]), size[1], thick(size[2])] : size;
  // The game draws glTF models mirrored in x (Babylon's import into its left-handed space), so the boxes are too.
  const boxes = collision ? collisionBoxes(p, size, sceneTriangles(scene))?.map(([x0, y0, z0, x1, y1, z1]) => [round(-x1), y0, z0, round(-x0), y1, z1]) : null;
  defs.push({ id: `prop.${p.id}`, file, displayName: p.name, category: p.category, size, collision, ...(boxes ? { boxes } : {}), ...(p.breakable && collision ? { breakable: p.breakable } : {}), ...(p.conceals ? { conceals: true } : {}) });
  lock.files.push({ file, source: p.pack, ...(p.budget ? { budget: p.budget } : {}), ...(p.source ? { title: `${p.source.model} (download dated ${p.source.date})` } : {}), src: Array.isArray(p.src) ? p.src.join(' + ') : p.src, triangles, ...(lodTriangles.length ? { lodTriangles } : {}), ...(pack.meshy && doc.getRoot().listMaterials().some((m) => m.getNormalTexture()) ? { normalMap: true } : {}), bytes: glb.byteLength, sha256: createHash('sha256').update(glb).digest('hex').slice(0, 16) , ...(external && !gltfKit ? { size } : {}) });
}

