// Builds the placeable props listed in content/props.json: each is centred on
// its footprint, stood on y = 0, scaled to its real-world height (or kept at
// the pack's own metric scale), and written as a self-contained GLB (textures
// embedded) to packages/client/public/props. Also writes
// content/props.lock.json (checked by `pnpm content:check`) and
// packages/shared/src/content/props.generated.ts, the sizes and collision
// boxes the simulation, bots and MapMaker use.
//
//   node tools/content/prepare-props.mjs [--downloads <dir>]
//
// Most packs live in assets-src/<pack>/. Packs with a `download` folder in
// content/props.json (the Quaternius Modular SciFi MegaKit) are too large to
// keep in the repo: their props are rebuilt only when --downloads points at a
// directory holding the extracted download (directly or one level down);
// otherwise the props already built from them are kept as they are.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Logger, NodeIO, getBounds } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, mergeDocuments, prune, simplify, weld } from '@gltf-transform/functions';
import { MeshoptSimplifier } from 'meshoptimizer';
import sharp from 'sharp';

await MeshoptSimplifier.ready;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'content/props.json'), 'utf8'));
const OUT = join(ROOT, 'packages/client/public/props');
const LOCK = join(ROOT, 'content/props.lock.json');
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const arg = process.argv.indexOf('--downloads');
const downloads = arg > 0 ? resolve(process.argv[arg + 1] ?? '') : null;
const oldLock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, 'utf8')) : { files: [] };

mkdirSync(OUT, { recursive: true });
const lock = { $comment: 'Generated by tools/content/prepare-props.mjs. Do not edit by hand.', files: [] };
const defs = [];
const round = (v) => Math.round(v * 1000) / 1000;
/** Steps and ramps are cut into boxes no taller than this, so players and bots walk up them (PLAYER.maxStepHeight is 0.3 m). */
const STEP_RISE = 0.25;
/** Thinnest collision box: single-sided kit walls are planes. */
const MIN_THICKNESS = 0.2;

/** The folder of an extracted download: directly under the downloads dir or one level down. */
function downloadDir(folder) {
  const direct = join(downloads, folder);
  if (existsSync(direct)) return direct;
  for (const d of readdirSync(downloads, { withFileTypes: true })) {
    if (d.isDirectory() && existsSync(join(downloads, d.name, folder))) return join(downloads, d.name, folder);
  }
  throw new Error(`${folder} not found in ${downloads}`);
}

/** Read a .gltf from a download whose images live in a separate folder (and whose buffer names may be off). */
async function readKitGltf(path, imageDir) {
  const json = JSON.parse(readFileSync(path, 'utf8'));
  const dir = dirname(path);
  const resources = {};
  for (const b of json.buffers ?? []) {
    let file = join(dir, decodeURIComponent(b.uri));
    // A few files name their buffer "<name>_001.bin" but ship "<name>.bin".
    if (!existsSync(file)) file = path.replace(/\.gltf$/, '.bin');
    resources[b.uri] = new Uint8Array(readFileSync(file));
  }
  for (const img of json.images ?? []) resources[img.uri] = new Uint8Array(readFileSync(join(imageDir, decodeURIComponent(img.uri))));
  const doc = await io.readJSON({ json, resources });
  doc.setLogger(quiet);
  return doc;
}

const quiet = new Logger(Logger.Verbosity.WARN);

/** Merge several kit pieces (a wall and its top) into the first document, in their shared kit space. */
async function readPieces(files, imageDir) {
  const [first, ...rest] = await Promise.all(files.map((f) => readKitGltf(f, imageDir)));
  for (const other of rest) {
    mergeDocuments(first, other);
    const scene = first.getRoot().listScenes()[0];
    const otherScene = first.getRoot().listScenes().at(-1);
    for (const n of otherScene.listChildren()) {
      otherScene.removeChild(n);
      scene.addChild(n);
    }
    otherScene.dispose();
  }
  // Merging leaves one buffer per source; GLB output needs exactly one.
  const [buffer, ...extra] = first.getRoot().listBuffers();
  for (const acc of first.getRoot().listAccessors()) acc.setBuffer(buffer);
  for (const b of extra) b.dispose();
  return first;
}

/**
 * Make a kit's materials cheap and self-contained: base colour downscaled to a
 * JPEG (PNG where it is cut out), normal map smaller still, metal/roughness
 * maps dropped for flat factors, decals cut out, glass see-through.
 */
async function bakeKitMaterials(doc, o) {
  const cache = new Map();
  const shrink = async (tex, size, alpha) => {
    const key = `${tex.getURI()}|${size}|${alpha}`;
    if (!cache.has(key)) {
      const img = sharp(Buffer.from(tex.getImage())).resize(size, size, { kernel: 'lanczos3' });
      cache.set(key, alpha ? await img.png({ palette: true, quality: 90 }).toBuffer() : await img.removeAlpha().jpeg({ quality: 82, mozjpeg: true }).toBuffer());
    }
    return { data: cache.get(key), mime: alpha ? 'image/png' : 'image/jpeg' };
  };
  for (const mat of doc.getRoot().listMaterials()) {
    const name = mat.getName();
    const decal = /Decal/i.test(name);
    mat.setMetallicRoughnessTexture(null).setOcclusionTexture(null);
    mat.setMetallicFactor(0).setRoughnessFactor(decal ? 0.8 : 0.6);
    for (const ext of mat.listExtensions()) ext.dispose();
    if (decal && mat.getBaseColorTexture()) mat.setAlphaMode('MASK').setAlphaCutoff(0.5);
    if (/Glass/i.test(name)) mat.setBaseColorFactor([0.55, 0.75, 0.85, 0.35]).setAlphaMode('BLEND').setRoughnessFactor(0.1);
    if (/^M_Light/.test(name) && mat.getEmissiveFactor().every((v) => v === 0)) mat.setEmissiveFactor(mat.getBaseColorFactor().slice(0, 3));
    const base = mat.getBaseColorTexture();
    if (base) {
      const r = await shrink(base, decal ? o.decalSize : o.textureSize, decal);
      base.setImage(r.data).setMimeType(r.mime).setURI('');
    }
    const normal = mat.getNormalTexture();
    if (normal && o.normalSize) {
      const r = await shrink(normal, o.normalSize, false);
      normal.setImage(r.data).setMimeType(r.mime).setURI('');
    } else if (normal) mat.setNormalTexture(null);
  }
  // Every texture gets a fresh name so dedup can merge identical images.
  for (const t of doc.getRoot().listTextures()) t.setName('');
}

/** Rotation quaternion of `deg` degrees about +Y (kit pieces face other ways than our props). */
const yawQuat = (deg) => [0, Math.sin((deg * Math.PI) / 360), 0, Math.cos((deg * Math.PI) / 360)];

/** Every triangle in the scene, in scene space, as three [x, y, z] points (for collision analysis). */
function sceneTriangles(scene) {
  const tris = [];
  const visit = (node) => {
    const m = node.getWorldMatrix();
    const mesh = node.getMesh();
    if (mesh)
      for (const prim of mesh.listPrimitives()) {
        const a = prim.getAttribute('POSITION').getArray();
        const at = (i) => {
          const [x, y, z] = [a[i * 3], a[i * 3 + 1], a[i * 3 + 2]];
          return [m[0] * x + m[4] * y + m[8] * z + m[12], m[1] * x + m[5] * y + m[9] * z + m[13], m[2] * x + m[6] * y + m[10] * z + m[14]];
        };
        const idx = prim.getIndices()?.getArray() ?? Array.from({ length: a.length / 3 }, (_, i) => i);
        for (let i = 0; i + 2 < idx.length; i += 3) tris.push([at(idx[i]), at(idx[i + 1]), at(idx[i + 2])]);
      }
    for (const c of node.listChildren()) visit(c);
  };
  for (const n of scene.listChildren()) visit(n);
  return tris;
}

/** Cell size of the `shell` collision grid (metres). */
const SHELL_CELL = 0.4;

/**
 * Collision that follows the model's footprint (corners, curved walls and
 * railings): the triangles are rasterised onto a grid seen from above, each
 * covered cell becomes a column as tall as the geometry in it, and runs of
 * cells are merged into as few boxes as possible.
 */
function shellBoxes(size, tris) {
  const [w, , d] = size;
  const nx = Math.max(1, Math.ceil(w / SHELL_CELL));
  const nz = Math.max(1, Math.ceil(d / SHELL_CELL));
  const top = new Float32Array(nx * nz);
  const cell = (x, z) => [Math.min(nx - 1, Math.max(0, Math.floor((x + w / 2) / SHELL_CELL))), Math.min(nz - 1, Math.max(0, Math.floor((z + d / 2) / SHELL_CELL)))];
  for (const [a, b, c] of tris) {
    const len = Math.max(Math.hypot(a[0] - b[0], a[2] - b[2]), Math.hypot(b[0] - c[0], b[2] - c[2]), Math.hypot(c[0] - a[0], c[2] - a[2]));
    const n = Math.max(1, Math.ceil(len / (SHELL_CELL / 3)));
    for (let i = 0; i <= n; i++)
      for (let j = 0; i + j <= n; j++) {
        const [u, v] = [i / n, j / n];
        const q = [0, 1, 2].map((k) => a[k] * (1 - u - v) + b[k] * u + c[k] * v);
        const [ix, iz] = cell(q[0], q[2]);
        top[iz * nx + ix] = Math.max(top[iz * nx + ix], q[1], 0.05);
      }
  }
  const used = new Uint8Array(nx * nz);
  const free = (ix, iz) => top[iz * nx + ix] > 0 && !used[iz * nx + ix];
  const boxes = [];
  for (let iz = 0; iz < nz; iz++)
    for (let ix = 0; ix < nx; ix++) {
      if (!free(ix, iz)) continue;
      let x1 = ix;
      while (x1 + 1 < nx && free(x1 + 1, iz)) x1++;
      let z1 = iz;
      while (z1 + 1 < nz && Array.from({ length: x1 - ix + 1 }, (_, k) => free(ix + k, z1 + 1)).every(Boolean)) z1++;
      let h = 0;
      for (let z = iz; z <= z1; z++)
        for (let x = ix; x <= x1; x++) {
          used[z * nx + x] = 1;
          h = Math.max(h, top[z * nx + x]);
        }
      boxes.push([-w / 2 + ix * SHELL_CELL, 0, -d / 2 + iz * SHELL_CELL, Math.min(w / 2, -w / 2 + (x1 + 1) * SHELL_CELL), h, Math.min(d / 2, -d / 2 + (z1 + 1) * SHELL_CELL)].map(round));
    }
  return boxes;
}

/**
 * Collision as several boxes in the prop's own space, [minX, minY, minZ, maxX, maxY, maxZ]:
 * `stairs` climb toward +Z (or +X with `climbs: "+x"`) in steps a player can walk up (ramps too); `frame`
 * keeps a doorway open between its posts and under its lintel; `shell` follows
 * the footprint (see shellBoxes).
 */
function collisionBoxes(p, size, tris) {
  const [w, h, d] = size;
  if (p.collide === 'shell') return shellBoxes(size, tris);
  const pts = tris.flat();
  if (p.collide === 'stairs') {
    const n = Math.max(1, Math.ceil(h / STEP_RISE));
    // `climbs: "+x"` for models whose steps rise along x instead of z.
    if (p.climbs === '+x') return Array.from({ length: n }, (_, i) => [-w / 2 + (w * i) / n, 0, -d / 2, w / 2, (h * (i + 1)) / n, d / 2].map(round));
    return Array.from({ length: n }, (_, i) => [-w / 2, 0, -d / 2 + (d * i) / n, w / 2, (h * (i + 1)) / n, d / 2].map(round));
  }
  if (p.collide === 'frame') {
    // The opening: the widest gap in x round the middle with no geometry below head height.
    const low = pts.filter((q) => q[1] > 0.3 && q[1] < 2);
    const inner = Math.min(...low.filter((q) => q[0] > 0).map((q) => q[0]), w / 2);
    const innerL = Math.max(...low.filter((q) => q[0] < 0).map((q) => q[0]), -w / 2);
    const top = Math.min(...pts.filter((q) => q[0] > innerL + 0.05 && q[0] < inner - 0.05 && q[1] > 1).map((q) => q[1]), h);
    const t = Math.max(d, MIN_THICKNESS) / 2;
    return [
      [-w / 2, 0, -t, innerL, h, t],
      [inner, 0, -t, w / 2, h, t],
      [innerL, top, -t, inner, h, t],
    ].map((b) => b.map(round));
  }
  return null;
}

const built = new Map(oldLock.files.map((f) => [f.file, f]));
for (const p of manifest.props) {
  const pack = manifest.packs[p.pack];
  const file = `props/${p.id}.glb`;
  const path = join(ROOT, 'packages/client/public', file);
  const external = !!pack.download;
  let glb;
  let size;
  if (external) {
    if (downloads) {
      const dir = downloadDir(pack.download);
      const srcs = Array.isArray(p.src) ? p.src : [p.src];
      const doc = await readPieces(srcs.map((s) => join(dir, pack.models, s)), join(dir, pack.images));
      await bakeKitMaterials(doc, pack);
      const scene = doc.getRoot().listScenes()[0];
      const turn = doc.createNode('turn').setRotation(yawQuat(p.yaw ?? 0));
      for (const child of scene.listChildren()) {
        scene.removeChild(child);
        turn.addChild(child);
      }
      scene.addChild(turn);
      const b = getBounds(scene);
      const s = p.height ? p.height / Math.max(1e-6, b.max[1] - b.min[1]) : (p.scale ?? 1);
      const root = doc.createNode('prop').setScale([s, s, s]).setTranslation([(-(b.min[0] + b.max[0]) / 2) * s, -b.min[1] * s + (p.lift ?? 0), (-(b.min[2] + b.max[2]) / 2) * s]);
      scene.removeChild(turn);
      root.addChild(turn);
      scene.addChild(root);
      await doc.transform(weld(), dedup(), ...(p.simplify ? [simplify({ simplifier: MeshoptSimplifier, ratio: p.simplify, error: 0.002 })] : []), prune());
      glb = Buffer.from(await io.writeBinary(doc));
      writeFileSync(path, glb);
    } else {
      // Not rebuilding this pack: keep the prop as built (already normalised) and measure it again.
      if (!existsSync(path)) throw new Error(`${file} is missing; rebuild it with --downloads <dir> (see docs/CONTENT_PIPELINE.md)`);
      glb = readFileSync(path);
      if (built.get(file)?.sha256 !== createHash('sha256').update(glb).digest('hex').slice(0, 16)) throw new Error(`${file} does not match content/props.lock.json; rebuild it with --downloads <dir>`);
    }
  } else {
    const doc = await io.read(join(ROOT, 'assets-src', p.pack, p.src));
    const scene = doc.getRoot().listScenes()[0];
    const b = getBounds(scene);
    const s = p.height / Math.max(1e-6, b.max[1] - b.min[1]);
    const cx = (b.min[0] + b.max[0]) / 2;
    const cz = (b.min[2] + b.max[2]) / 2;
    const root = doc.createNode('prop').setScale([s, s, s]).setTranslation([-cx * s, -b.min[1] * s, -cz * s]);
    for (const child of scene.listChildren()) {
      scene.removeChild(child);
      root.addChild(child);
    }
    scene.addChild(root);
    await doc.transform(weld(), dedup(), prune());
    glb = Buffer.from(await io.writeBinary(doc));
    writeFileSync(path, glb);
    size = [round((b.max[0] - b.min[0]) * s), round(p.height), round((b.max[2] - b.min[2]) * s)];
  }
  // Measure what was written (the same whether it was just built or kept).
  const doc = await io.readBinary(new Uint8Array(glb));
  const scene = doc.getRoot().listScenes()[0];
  let triangles = 0;
  for (const mesh of doc.getRoot().listMeshes()) for (const prim of mesh.listPrimitives()) triangles += (prim.getIndices()?.getCount() ?? prim.getAttribute('POSITION').getCount()) / 3;
  if (!size) {
    const b = getBounds(scene);
    // Flat pieces (floor plates, decals) are lifted a little off the floor; their footprint still starts at 0.
    size = [round(b.max[0] - b.min[0]), round(Math.max(b.max[1], 0.01)), round(b.max[2] - b.min[2])];
  }
  const thick = (v) => round(Math.max(v, MIN_THICKNESS));
  const collision = p.collide === 'none' ? null : p.collide === 'trunk' ? [Math.min(0.5, size[0]), size[1], Math.min(0.5, size[2])] : external ? [thick(size[0]), size[1], thick(size[2])] : size;
  // The game draws glTF models mirrored in x (Babylon's import into its left-handed space), so the boxes are too.
  const boxes = collision ? collisionBoxes(p, size, sceneTriangles(scene))?.map(([x0, y0, z0, x1, y1, z1]) => [round(-x1), y0, z0, round(-x0), y1, z1]) : null;
  defs.push({ id: `prop.${p.id}`, file, displayName: p.name, category: p.category, size, collision, ...(boxes ? { boxes } : {}), ...(p.breakable && collision ? { breakable: p.breakable } : {}) });
  lock.files.push({ file, source: p.pack, src: Array.isArray(p.src) ? p.src.join(' + ') : p.src, triangles, bytes: glb.byteLength, sha256: createHash('sha256').update(glb).digest('hex').slice(0, 16) });
}

// Files left behind by renamed or removed props.
const keep = new Set(lock.files.map((f) => f.file));
for (const f of readdirSync(OUT)) if (!keep.has(`props/${f}`)) rmSync(join(OUT, f), { recursive: true, force: true });

writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
const categories = [...new Set(manifest.props.map((p) => p.category))];
writeFileSync(
  join(ROOT, 'packages/shared/src/content/props.generated.ts'),
  `// Generated by tools/content/prepare-props.mjs from content/props.json. Do not edit by hand.
import type { PropDefinition } from './props.ts';

export const PROP_CATEGORIES = [${categories.map((c) => `'${c}'`).join(', ')}] as const;

export const CORE_PROPS: readonly PropDefinition[] = [
${defs.map((d) => `  ${JSON.stringify(d).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\w+: )/g, ', ').replace(/"/g, "'")},`).join('\n')}
];
`,
);
console.log(`wrote ${defs.length} props${downloads ? '' : ' (packs from downloads kept as built)'}`);
