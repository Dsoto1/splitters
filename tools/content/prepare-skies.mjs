// Builds the sky backdrops listed in content/skies.json: downloads each CC0
// tonemapped photo from Poly Haven (cached in .cache/skies), scales it to a
// 2048 × 1024 equirectangular JPEG in packages/client/public/skies, and
// writes packages/shared/src/content/skies.generated.ts with each sky's
// horizon and zenith colours (for haze and fog) and its lighting.
//
//   node tools/content/prepare-skies.mjs

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'content/skies.json'), 'utf8'));
const CACHE = join(ROOT, '.cache/skies');
const OUT = join(ROOT, 'packages/client/public/skies');
mkdirSync(CACHE, { recursive: true });
mkdirSync(OUT, { recursive: true });

const hex = (rgb) => `#${rgb.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('')}`;
const defs = [];
const lock = { $comment: 'Generated by tools/content/prepare-skies.mjs. Do not edit by hand.', files: [] };
for (const s of manifest.skies) {
  const src = join(CACHE, `${s.source}.jpg`);
  if (!existsSync(src)) {
    const url = `https://dl.polyhaven.org/file/ph-assets/HDRIs/extra/Tonemapped%20JPG/${s.source}.jpg`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: ${res.status}`);
    writeFileSync(src, Buffer.from(await res.arrayBuffer()));
  }
  const graded = () => {
    const img = sharp(src, { limitInputPixels: false });
    return s.grade ? img.linear(s.grade, [0, 0, 0]) : img;
  };
  const jpg = await graded().resize(2048, 1024).jpeg({ quality: 82, mozjpeg: true }).toBuffer();
  writeFileSync(join(OUT, `${s.id}.jpg`), jpg);
  lock.files.push({ file: `skies/${s.id}.jpg`, source: s.id, src: `${s.source}.jpg`, bytes: jpg.byteLength, sha256: createHash('sha256').update(jpg).digest('hex').slice(0, 16) });
  // Colours: average a band just above the horizon, and the top of the sky.
  const { data, info } = await sharp(await graded().resize(64, 32).png().toBuffer()).raw().toBuffer({ resolveWithObject: true });
  const band = (y0, y1) => {
    const sum = [0, 0, 0];
    let n = 0;
    for (let y = y0; y < y1; y++) {
      for (let x = 0; x < info.width; x++) {
        for (let k = 0; k < 3; k++) sum[k] += data[(y * info.width + x) * info.channels + k];
        n++;
      }
    }
    return sum.map((v) => v / n);
  };
  defs.push({ id: s.id, name: s.name, file: `skies/${s.id}.jpg`, horizon: hex(band(13, 16)), zenith: hex(band(1, 5)), light: s.light });
}
writeFileSync(join(ROOT, 'content/skies.lock.json'), `${JSON.stringify(lock, null, 2)}\n`);
writeFileSync(
  join(ROOT, 'packages/shared/src/content/skies.generated.ts'),
  `// Generated by tools/content/prepare-skies.mjs from content/skies.json. Do not edit by hand.
import type { SkyDefinition } from '../map/backdrop.ts';

export const PHOTO_SKIES: readonly SkyDefinition[] = [
${defs.map((d) => `  ${JSON.stringify(d).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\w+: )/g, ', ').replace(/"/g, "'")},`).join('\n')}
];
`,
);
console.log(`wrote ${defs.length} skies`);
