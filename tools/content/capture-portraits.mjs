// Renders every built-in character's portrait for Character Select, so the site ships them as small
// pictures instead of building each 3D character in the player's browser (which took a while):
//   packages/client/public/portraits/<look>.webp      192×192 WebP, transparent background
//   packages/client/src/frontend/portraitIndex.ts      which looks have one (and a hash, so a new one is fetched)
// The pictures come from the same renderer the menu uses (frontend/portraits.ts, renderLive): framing
// fixes there show up here on the next capture. A player's own designs are still rendered live.
//
// Run against a built client being served (the "Capture portraits" workflow does all of this):
//   pnpm build && pnpm --filter @tiletrigger/client exec vite preview --port 4799
//   node tools/content/capture-portraits.mjs http://localhost:4799 [look ids…]
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = join(ROOT, 'packages/client/public/portraits');
const INDEX = join(ROOT, 'packages/client/src/frontend/portraitIndex.ts');
const base = process.argv[2] ?? 'http://localhost:4799';
const only = process.argv.slice(3);
/** Shipped size (the menus show them at 46–120 px; 192 stays sharp on high-density screens). */
const SIZE = 192;

/** A look ID as a file name (IDs are like core.nova or npc:soldier). */
const fileOf = (look) => `${look.replace(/[^A-Za-z0-9_.-]/g, '_')}.webp`;

mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${base}/?test=1&name=Tester`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__front, null, { timeout: 120_000 });
const looks = (await page.evaluate(() => window.__front.portraitLooks())).filter((l) => !only.length || only.includes(l));
console.log(`${looks.length} portraits`);

// The index: a full run starts it again (pictures of looks that are gone are deleted); a partial run
// (look ids on the command line) keeps the other entries as they were.
const index = {};
if (only.length) for (const m of readFileSync(INDEX, 'utf8').matchAll(/^ {2}'([^']+)': '([^']+)',$/gm)) index[m[1]] = m[2];
const failed = [];
for (const look of looks) {
  const t0 = Date.now();
  const url = await page.evaluate((l) => window.__front.portraits.renderLive(l), look).catch((e) => {
    failed.push(`${look}: ${e.message}`);
    return null;
  });
  if (!url) continue;
  const png = Buffer.from(url.slice(url.indexOf(',') + 1), 'base64');
  const webp = await sharp(png).resize(SIZE, SIZE).webp({ quality: 84, alphaQuality: 90 }).toBuffer();
  writeFileSync(join(OUT, fileOf(look)), webp);
  index[look] = `${fileOf(look)}?v=${createHash('sha256').update(webp).digest('hex').slice(0, 10)}`;
  console.log(`${look}: ${(webp.length / 1024).toFixed(1)} kB (${Date.now() - t0} ms)`);
}
await browser.close();
if (!only.length) {
  const keep = new Set(Object.values(index).map((v) => v.split('?')[0]));
  for (const f of readdirSync(OUT)) if (f.endsWith('.webp') && !keep.has(f)) rmSync(join(OUT, f));
}

const lines = Object.keys(index)
  .sort()
  .map((k) => `  '${k}': '${index[k]}',`);
writeFileSync(
  INDEX,
  `/**
 * Portraits shipped with the site (public/portraits/), by look ID: the file
 * and a hash of it (so a new picture is fetched, not a cached old one).
 * Generated by tools/content/capture-portraits.mjs (the "Capture portraits"
 * workflow) from the same renderer the menu uses; a look missing here (new
 * since the last capture, or a player's own design) is rendered live.
 */
export const SHIPPED_PORTRAITS: Readonly<Record<string, string>> = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`,
);
console.log(`index: ${Object.keys(index).length} portraits`);
if (failed.length || errors.length) {
  console.error(`failed: ${failed.join('; ')}${errors.length ? ` · page errors: ${errors.join('; ')}` : ''}`);
  process.exit(1);
}
